// Image-model pin check — `npm run images:check`.
//
// WHY THIS EXISTS: the image models in lib/images/tiers.ts are pinned by hand
// (OpenAI has no alias we can safely float on), and OpenAI retires models on a
// calendar — gpt-image-1 went dark 2026-10-23; gpt-image-1.5 and gpt-image-1-mini
// follow on 2026-12-01. A retired pin gives no warning: the next generation just
// fails. This script makes the rot visible by asking OpenAI whether each pinned
// model is still served. It never edits the pins — the decision stays human.
//
//   npm run images:check                  free: one GET /v1/models/<id> per pin
//   npm run images:check -- --generate    ALSO one real generation per pin
//                                         (1024x1024, quality low, WebP out;
//                                         about a cent each) to prove the Images
//                                         API still accepts the request shape the
//                                         app sends and returns a real WebP
//
// The pins are read out of lib/images/tiers.ts as text, so this script can never
// disagree with the app about what is pinned. Plain fetch, no SDK, no file
// writes (the generated bytes are measured and dropped). Exit 0 = every pin was
// found (and, with --generate, generated); exit 1 = a pin is missing, a call
// failed, or OPENAI_API_KEY is unset.

import { readFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'

const TIERS_PATH = new URL('../lib/images/tiers.ts', import.meta.url)
const API = 'https://api.openai.com/v1'
const LOOKUP_TIMEOUT_MS = 30_000
// OpenAI says complex prompts on the 2.5 models can take up to 2 minutes.
const GENERATE_TIMEOUT_MS = 180_000

// Pull the pinned model ids straight out of the tiers file. Only the IMAGE_TIERS
// literal is scanned — the header comment above it names retired models too.
export async function pinnedModels() {
  const src = await readFile(TIERS_PATH, 'utf8')
  const start = src.indexOf('export const IMAGE_TIERS')
  if (start < 0) throw new Error('IMAGE_TIERS not found in lib/images/tiers.ts')
  const found = [...src.slice(start).matchAll(/\bmodel:\s*'([^']+)'/g)].map((m) => m[1])
  return [...new Set(found)]
}

function authHeaders(key) {
  return { Authorization: `Bearer ${key}` }
}

// GET /v1/models/<id>. 200 = served; 404 = not served to this key (retired, or
// the project has no access to it); anything else is an ERROR, not a verdict.
async function lookup(key, id) {
  let res
  try {
    res = await fetch(`${API}/models/${encodeURIComponent(id)}`, {
      headers: authHeaders(key),
      signal: AbortSignal.timeout(LOOKUP_TIMEOUT_MS),
    })
  } catch (err) {
    return { status: 'ERROR', detail: `request failed - ${err?.message ?? err}` }
  }
  if (res.ok) return { status: 'FOUND' }
  const body = await res.json().catch(() => null)
  const detail = body?.error?.message ?? `HTTP ${res.status}`
  return { status: res.status === 404 ? 'MISSING' : 'ERROR', detail }
}

// One real generation, shaped like the app's own call (lib/images/openai.ts):
// n 1, WebP out at compression 90. Quality is 'low' and the size is the smallest
// square so it costs about a cent.
async function probeGenerate(key, id) {
  let res
  try {
    res = await fetch(`${API}/images/generations`, {
      method: 'POST',
      headers: { ...authHeaders(key), 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model: id,
        prompt: 'A plain wooden bench beside a window, soft morning light.',
        n: 1,
        size: '1024x1024',
        quality: 'low',
        output_format: 'webp',
        output_compression: 90,
      }),
      signal: AbortSignal.timeout(GENERATE_TIMEOUT_MS),
    })
  } catch (err) {
    return { ok: false, detail: `request failed - ${err?.message ?? err}` }
  }
  const body = await res.json().catch(() => null)
  if (!res.ok) return { ok: false, detail: body?.error?.message ?? `HTTP ${res.status}` }
  const b64 = body?.data?.[0]?.b64_json
  if (!b64) return { ok: false, detail: 'the response carried no image data' }
  const bytes = Buffer.from(b64, 'base64')
  // The app stores image/webp and verifies the magic bytes, so a PNG here would
  // fail in production even though the call succeeded.
  const isWebp = bytes.subarray(0, 4).toString('latin1') === 'RIFF' && bytes.subarray(8, 12).toString('latin1') === 'WEBP'
  if (!isWebp) return { ok: false, detail: `${bytes.length} bytes came back, but they are not a WebP` }
  return { ok: true, detail: `${bytes.length} bytes (webp), usage ${JSON.stringify(body.usage ?? null)}` }
}

async function main() {
  const generate = process.argv.includes('--generate')

  const pins = await pinnedModels()
  if (!pins.length) {
    console.error('FAIL: could not parse any models out of lib/images/tiers.ts')
    process.exit(1)
  }
  console.log(`tiers.ts pins ${pins.length} image models: ${pins.join(', ')}\n`)

  const key = process.env.OPENAI_API_KEY
  if (!key) {
    console.error('FAIL: OPENAI_API_KEY is not set. `npm run images:check` loads it from your local env file.')
    process.exit(1)
  }

  let problems = 0
  for (const id of pins) {
    const found = await lookup(key, id)
    if (found.status === 'FOUND') {
      console.log(`FOUND    ${id}`)
    } else {
      problems++
      console.log(`${found.status.padEnd(8)} ${id} - ${found.detail}`)
    }

    // A MISSING pin cannot generate; an ERROR (say, a restricted key that cannot
    // read models) still can, so the probe is the way to settle it.
    if (generate && found.status !== 'MISSING') {
      const gen = await probeGenerate(key, id)
      if (gen.ok) {
        console.log(`         generate OK   ${id} - ${gen.detail}`)
      } else {
        problems++
        console.log(`         generate FAIL ${id} - ${gen.detail}`)
      }
    }
  }

  if (problems) {
    console.error(
      `\nIMAGE CHECK FAIL: ${problems} problem(s). A MISSING pin will fail at runtime - ` +
        'update lib/images/tiers.ts (and the rows in lib/ai/pricing.ts), then run this again.',
    )
    process.exitCode = 1
    return
  }
  console.log(`\nIMAGE CHECK PASS - ${pins.length} pinned model(s) found${generate ? ' and generating' : ''}`)
}

// Only run when invoked directly, so pinnedModels() can be imported without
// touching the network.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error('FAIL:', err?.message ?? err)
    process.exit(1)
  })
}
